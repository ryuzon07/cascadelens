"""Realised drop rates and edge counts against nominal, for a parameter grid."""

from collections.abc import Sequence
from pathlib import Path
from typing import Any

from cascadelens.baselines.runner import load_dataset
from cascadelens.perturb.base import ManifestRow
from cascadelens.perturb.registry import REFERENCES, grid, load_suite
from cascadelens.perturb.store import Summary, apply_to

SUMMARY_PATH = Path("docs/perturbation_summary.md")


def _ratio(top: int, bottom: int) -> float | None:
    return top / bottom if bottom else None


def _mean(rows: Sequence[ManifestRow], key: str) -> float | None:
    values = [row.details[key] for row in rows if row.details.get(key) is not None]
    return sum(values) / len(values) if values else None


def _cell(value: float | None, digits: int = 3) -> str:
    return "-" if value is None else f"{value:.{digits}f}"


def describe(
    realism: str, identifier: str, params: dict[str, Any], result: Summary
) -> dict[str, Any]:
    """Return one line of the summary."""
    rows = result.rows
    edges = sum(row.edges_before for row in rows)
    return {
        "id": identifier,
        "params": ", ".join(f"{key}={value}" for key, value in sorted(params.items())) or "default",
        "realism": realism,
        "nominal": params.get("rate"),
        "sample_share": _ratio(
            sum(row.samples_dropped for row in rows), sum(row.samples_before for row in rows)
        ),
        "series_share": _ratio(
            sum(row.series_dropped for row in rows), sum(row.series_before for row in rows)
        ),
        "edges_before": edges / len(rows),
        "edges_removed": _ratio(sum(row.edges_removed for row in rows), edges),
        "edges_added": _ratio(sum(row.edges_added for row in rows), edges),
        "near_rate": _mean(rows, "near_rate"),
        "far_rate": _mean(rows, "far_rate"),
        "before_rate": _mean(rows, "before_rate"),
        "after_rate": _mean(rows, "after_rate"),
        "bytes": result.bytes,
    }


def summarize(
    root: Path = Path(), workers: int = 1, max_cases: int | None = None
) -> list[dict[str, Any]]:
    """Build the suite's grid over the dataset and write ``docs/perturbation_summary.md``."""
    suite = load_suite(root)
    dataset = load_dataset(root)
    ids = sorted(dataset.records)
    chosen = ids if max_cases is None else ids[:: max(1, len(ids) // max_cases)][:max_cases]
    lines = []
    for spec, params in grid(suite):
        result = apply_to(spec.id, params, suite.seed, chosen, root, workers)
        lines.append(describe(spec.realism, spec.id, params, result))
    _write_report(lines, len(chosen), suite.seed, root)
    return lines


def _write_report(lines: list[dict[str, Any]], cases: int, seed: int, root: Path) -> None:
    total = sum(line["bytes"] for line in lines)
    text = [
        "# Perturbation summary",
        "",
        "Generated by `cascadelens perturb summarize`. Do not edit by hand.",
        "",
        f"{cases} cases, seed {seed}. Every row is labelled simulated or held-out. The benchmark "
        "has a static topology, so topology rows describe an imperfect graph, not a changing one.",
        "",
        "Sample share is the share of real samples dropped, and series share the share of series "
        "with data left with none. RE1 records no graph, so edge rows start from the inferred "
        "graph.",
        "",
        "## Realised against nominal",
        "",
        "| Id | Parameters | Label | Nominal | Sample share | Series share | Size (MB) |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for line in lines:
        text.append(
            f"| {line['id']} | {line['params']} | {line['realism']} | {_cell(line['nominal'], 2)} "
            f"| {_cell(line['sample_share'])} | {_cell(line['series_share'])} "
            f"| {line['bytes'] / 1e6:.0f} |"
        )
    text += [
        "",
        "## P2 by zone",
        "",
        "Mean per case of the realised drop rate.",
        "",
        "| Parameters | Label | Near | Far | Before injection | After injection |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for line in lines:
        if line["id"] == "P2":
            text.append(
                f"| {line['params']} | {line['realism']} | {_cell(line['near_rate'])} "
                f"| {_cell(line['far_rate'])} | {_cell(line['before_rate'])} "
                f"| {_cell(line['after_rate'])} |"
            )
    text += [
        "",
        "## Edges",
        "",
        "| Id | Parameters | Label | Mean edges before | Removed share | Added share |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for line in lines:
        if line["id"] in ("P6", "P7", "P8"):
            text.append(
                f"| {line['id']} | {line['params']} | {line['realism']} "
                f"| {line['edges_before']:.1f} | {_cell(line['edges_removed'])} "
                f"| {_cell(line['edges_added'])} |"
            )
    text += ["", "## Held-out conditions", "", "| Id | Name | Split | Label |"]
    text.append("| --- | --- | --- | --- |")
    text += [
        f"| {item.id} | {item.name} | {item.split} | {item.realism} |"
        for item in REFERENCES.values()
    ]
    text += [
        "",
        "## Disk",
        "",
        f"The grid takes {total / 1e9:.2f} GB for {cases} cases at one seed. Datasets are built on "
        "first use and cached by content hash, and topology rows store no metrics.",
        "",
    ]
    path = root / SUMMARY_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(text))
