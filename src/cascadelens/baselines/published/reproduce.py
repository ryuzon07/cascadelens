"""The reproduction run: the paper's protocol on raw RE1 files, scored by RCAEval's own code.

This is the one place that reads ``inject_time``, because the protocol being reproduced is given
that time. Steps follow ``process()`` in RCAEval's ``main.py`` at the pinned version, and the
published numbers come from ASE 2024, Table 5 (see docs/reproduction/PLAN.md).
"""

import statistics
import time
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from cascadelens.baselines.base import BaselineError
from cascadelens.baselines.experiments import _write_text
from cascadelens.config import BaselineConfig, StrictModel, load_config
from cascadelens.data.io import read_manifest
from cascadelens.results import write_result
from cascadelens.seed import derive_case_seed, set_seed

FAULTS = ("cpu", "mem", "disk", "delay", "loss")
SUITES = {"RE1-OB": "re1-ob", "RE1-SS": "re1-ss", "RE1-TT": "re1-tt"}
PUBLISHED_AVG5: dict[str, dict[str, tuple[float, ...]]] = {
    "baro": {
        "RE1-OB": (0.97, 1.00, 0.91, 0.98, 0.67),
        "RE1-SS": (1.00, 0.98, 0.94, 0.98, 0.87),
        "RE1-TT": (0.90, 0.96, 0.84, 0.77, 0.66),
    },
    "lingam_randomwalk": {
        "RE1-OB": (0.40, 0.37, 0.34, 0.14, 0.20),
        "RE1-SS": (0.48, 0.46, 0.49, 0.45, 0.36),
        "RE1-TT": (0.16, 0.05, 0.11, 0.03, 0.13),
    },
}
TOLERANCE = 0.05
RESULT_DIR = Path("experiments/reproduction")
DOCS_DIR = Path("docs/reproduction")
RAW_DIR = Path("data/raw")


class ReproductionConfig(StrictModel):
    """Settings of one reproduction run. ``length`` is ``main.py``'s ``--length``."""

    method: str
    seeds: list[int]
    length: int = 20
    data_file: str = "data.csv"


@dataclass(frozen=True)
class CaseResult:
    """One scored case."""

    suite: str
    fault: str
    service: str
    ranks: list[str]
    seconds: float


def compare(method: str, scores: dict[str, dict[str, float]]) -> dict[str, dict[str, Any]]:
    """Compare per-fault Avg@5 with the published values, under the tolerance of the plan."""
    rows: dict[str, dict[str, Any]] = {}
    for suite, published in PUBLISHED_AVG5[method].items():
        ours = [scores[suite][fault] for fault in FAULTS]
        published_mean = statistics.fmean(published)
        our_mean = statistics.fmean(ours)
        rows[suite] = {
            "published": dict(zip(FAULTS, published, strict=True)),
            "ours": dict(zip(FAULTS, ours, strict=True)),
            "published_mean": published_mean,
            "our_mean": our_mean,
            "difference": our_mean - published_mean,
            "passed": abs(our_mean - published_mean) <= TOLERANCE,
        }
    return rows


def render(
    method: str,
    rows: dict[str, dict[str, Any]],
    accuracy: dict[str, float],
    failed: int,
    seconds: dict[str, float],
    length: int,
    data_file: str,
    notes: str,
) -> str:
    """Render the published-versus-ours report."""
    verdict = "PASS" if all(row["passed"] for row in rows.values()) else "FAIL"
    lines = [
        f"# Reproduction: {method}",
        "",
        "Generated by `cascadelens published reproduce`. Do not edit the tables by hand; the "
        f"causes below come from `experiments/reproduction/{method}/notes.md`.",
        "",
        f"**Result: {verdict}**, with tolerance {100 * TOLERANCE:g} Avg@5 points on each system "
        f"mean. Protocol: `main.py --length {length}` at RCAEval 1.11.0, with the true "
        f"`inject_time`, reading `{data_file}` where a case has one and `data.csv` otherwise. "
        "Published values: ASE 2024, Table 5, PDF page 7.",
        "",
        "| System | Published | Ours | Difference | Tolerance | Result | Our AC@1 | Seconds/case |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for suite, row in rows.items():
        lines.append(
            f"| {suite} | {row['published_mean']:.3f} | {row['our_mean']:.3f} "
            f"| {row['difference']:+.3f} | {TOLERANCE:.2f} "
            f"| {'pass' if row['passed'] else 'FAIL'} | {accuracy[suite]:.3f} "
            f"| {seconds[suite]:.3f} |"
        )
    lines += [
        "",
        "No published AC@1 exists for RE1 in these papers, so ours has no comparison.",
        "",
        "Per fault, published / ours:",
        "",
        "| System | " + " | ".join(fault.upper() for fault in FAULTS) + " |",
        "| --- | " + " | ".join("---" for _ in FAULTS) + " |",
    ]
    for suite, row in rows.items():
        cells = " | ".join(f"{row['published'][f]:.2f} / {row['ours'][f]:.2f}" for f in FAULTS)
        lines.append(f"| {suite} | {cells} |")
    lines += ["", f"Failed cases: {failed}.", "", "## Causes of any gap", "", notes.strip()]
    return "\n".join(lines) + "\n"


def _load_case(path: Path, length: int) -> tuple[Any, int]:
    """Apply the data steps of ``main.py``, in its order."""
    import numpy as np
    import pandas as pd

    data = pd.read_csv(path)
    if "time.1" in data:
        data = data.drop(columns=["time.1"])
    data = data.loc[:, ~data.columns.str.endswith("_latency-50")]
    data = data.replace([np.inf, -np.inf], np.nan).ffill().fillna(0)
    inject_time = int((path.parent / "inject_time.txt").read_text().splitlines()[0].strip())
    half = length * 60 // 2
    normal = data[data["time"] < inject_time].tail(half)
    anomalous = data[data["time"] >= inject_time].head(half)
    window = pd.concat([normal, anomalous], ignore_index=True)
    renamed = {c: c.replace("_latency-90", "_latency") for c in window.columns}
    return window.rename(columns=renamed), inject_time


def _run_suite(
    config: ReproductionConfig, suite: str, dataset: str, seed: int, raw_dir: Path
) -> tuple[list[CaseResult], int]:
    from RCAEval import e2e

    method = getattr(e2e, config.method)
    results, failed = [], 0
    paths = sorted((raw_dir / suite).glob("*/*/data.csv"), key=lambda p: p.as_posix())
    for path in paths:
        service, fault = path.parents[1].name.rsplit("_", 1)
        chosen = path.with_name(config.data_file)
        data, inject_time = _load_case(chosen if chosen.is_file() else path, config.length)
        set_seed(derive_case_seed(path.as_posix(), config.method, {}, seed))
        start = time.perf_counter()
        try:
            output = method(
                data,
                inject_time,
                dataset=dataset,
                anomalies=None,
                dk_select_useful=False,
                sli=None,
                verbose=False,
                n_iter=len(data.columns) - 1,
            )
        except Exception:
            failed += 1
            continue
        adjacency = output.get("adj")
        if isinstance(adjacency, list) and not adjacency:
            failed += 1
            continue
        results.append(
            CaseResult(suite, fault, service, output["ranks"], time.perf_counter() - start)
        )
    return results, failed


def _scores(results: list[CaseResult]) -> tuple[dict[str, float], float]:
    """Score with RCAEval's evaluator: Avg@5 per fault, and AC@1 over the suite."""
    from RCAEval.benchmark.evaluation import Evaluator
    from RCAEval.benchmark.scoring import service_ranks
    from RCAEval.classes.graph import Node

    by_fault: dict[str, Any] = defaultdict(lambda: Evaluator(max_k=5))
    overall = Evaluator(max_k=5)
    for result in results:
        ranks = service_ranks(result.ranks)
        answer = Node(result.service, "unknown")
        by_fault[result.fault].add_case(ranks=ranks, answer=answer)
        overall.add_case(ranks=ranks, answer=answer)
    return {f: float(by_fault[f].average(5)) for f in FAULTS}, float(overall.accuracy(1))


def reproduce(name: str, root: Path = Path()) -> dict[str, object]:
    """Run one method's reproduction, averaging scores over its seeds."""
    if name not in PUBLISHED_AVG5:
        raise BaselineError(f"No published numbers for {name!r}")
    directory = root / RESULT_DIR / name
    config = load_config(directory / "config.yaml", ReproductionConfig)
    raw_dir = root / RAW_DIR
    per_seed: list[dict[str, dict[str, float]]] = []
    seed_accuracy: dict[str, list[float]] = defaultdict(list)
    seconds: dict[str, list[float]] = defaultdict(list)
    failed = 0
    for seed in config.seeds:
        scores: dict[str, dict[str, float]] = {}
        for suite, dataset in SUITES.items():
            results, misses = _run_suite(config, suite, dataset, seed, raw_dir)
            failed += misses
            scores[suite], accuracy = _scores(results)
            seed_accuracy[suite].append(accuracy)
            seconds[suite] += [result.seconds for result in results]
        per_seed.append(scores)
    averaged = {
        suite: {f: statistics.fmean(s[suite][f] for s in per_seed) for f in FAULTS}
        for suite in SUITES
    }
    ac1 = {suite: statistics.fmean(seed_accuracy[suite]) for suite in SUITES}
    speed = {suite: statistics.fmean(seconds[suite]) for suite in SUITES}
    rows = compare(name, averaged)
    notes_path = directory / "notes.md"
    notes = notes_path.read_text(encoding="utf-8") if notes_path.is_file() else "To be written."
    text = render(name, rows, ac1, failed, speed, config.length, config.data_file, notes)
    _write_text(root / DOCS_DIR / f"{name}.md", text)
    payload: dict[str, object] = {
        "comparison": rows,
        "ac1": ac1,
        "data_file": config.data_file,
        "per_seed": per_seed,
        "failed_cases": failed,
        "seconds_per_case": speed,
    }
    checksum = read_manifest(root / "data" / "processed").digest()
    settings = BaselineConfig(name=name, supervised=False, seeds=config.seeds)
    write_result(directory / "results.json", payload, settings, config.seeds[0], checksum)
    return payload
