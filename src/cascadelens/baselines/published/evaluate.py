"""The evaluation run: same splits, windows and cases as the other baselines.

Results stay apart from supervised methods. Tables reuse the clean-baseline rendering, so every
method is summarized the same way.
"""

from pathlib import Path

import polars as pl

from cascadelens.baselines.base import BaselineError
from cascadelens.baselines.experiments import (
    ExperimentConfig,
    MethodRuns,
    _floor,
    _fold_rows,
    _summaries,
    _table,
    _with_held_out,
    _write_text,
)
from cascadelens.baselines.published.baro import Baro, BaroKeyMetrics, BaroMidpoint
from cascadelens.baselines.published.base import PublishedBaseline
from cascadelens.baselines.published.lingam_randomwalk import LingamRandomWalk
from cascadelens.baselines.runner import load_dataset, load_split, run_folds
from cascadelens.config import BaselineConfig, load_config
from cascadelens.results import write_result

PUBLISHED: dict[str, type[PublishedBaseline]] = {
    method.name: method for method in (Baro, BaroKeyMetrics, BaroMidpoint, LingamRandomWalk)
}
CONFIG_DIR = Path("configs/baselines")
EVALUATION_DIR = Path("experiments/reproduction/evaluation")
SENSITIVITY = "baro_midpoint"


def load_published_config(name: str, root: Path = Path()) -> BaselineConfig:
    """Read the config of a published wrapper."""
    path = root / CONFIG_DIR / f"{name}.yaml"
    if name not in PUBLISHED or not path.is_file():
        raise BaselineError(f"Unknown published method {name!r}; choose from {sorted(PUBLISHED)}")
    return load_config(path, BaselineConfig)


def _runs(
    baseline: PublishedBaseline, config: BaselineConfig, split: str, root: Path
) -> tuple[MethodRuns, list[dict[str, object]]]:
    dataset = load_dataset(root)
    saved, group_map = load_split(split, dataset, root)
    frames, predictions = [], None
    details = []
    for seed in config.seeds:
        run = run_folds(baseline, config, saved, group_map, dataset, seed)
        frames.append(run.outcomes.with_columns(seed=pl.lit(seed)))
        predictions = run.predictions
        details.append(run.metrics)
    assert predictions is not None
    return MethodRuns(config.name, split, pl.concat(frames), predictions), details


def _operational(baseline: PublishedBaseline) -> dict[str, object]:
    runtimes = sorted(baseline.runtimes.values())
    return {
        "failed_cases": len({failure.case_id for failure in baseline.failures}),
        "failures": [vars(failure) for failure in baseline.failures],
        "mean_seconds_per_case": sum(runtimes) / len(runtimes) if runtimes else 0.0,
        "max_seconds_per_case": runtimes[-1] if runtimes else 0.0,
    }


def evaluate_published(root: Path = Path()) -> dict[str, object]:
    """Run each configured method on group_run, LOFO and LOSO, and write the tables."""
    directory = root / EVALUATION_DIR
    config = load_config(directory / "config.yaml", ExperimentConfig)
    pooled: list[dict[str, object]] = []
    folds: list[dict[str, object]] = []
    operational: dict[str, object] = {}
    for method in config.methods:
        settings = load_published_config(method, root)
        baseline = PUBLISHED[method]()
        for split in ("group_run", "lofo", "loso"):
            runs, _ = _runs(baseline, settings, split, root)
            labelled = _with_held_out(runs, root, split)
            if split == "group_run":
                pooled.append(
                    {
                        "method": method,
                        "split": split,
                        "fold": "pooled",
                        "cases": labelled.outcomes["case_id"].n_unique(),
                        "floor": _floor(labelled.predictions),
                        **_summaries(labelled.outcomes, config),
                    }
                )
            else:
                folds += _fold_rows(method, labelled, split, config)
        operational[method] = _operational(baseline)
    lines = [
        "# Published baselines: evaluation run",
        "",
        "Generated by `cascadelens published evaluate`. Unsupervised methods, on the same splits, "
        "windows and cases as `experiments/baselines_clean`. Scores are percentages with 95% "
        "group-bootstrap intervals, averaged per case over each method's seeds.",
        "",
        "`baro` sees every metric, like the other baselines, and splits normal from anomalous at "
        "25% of the window, computed without `inject_time`. `lingam_randomwalk` uses no anomaly "
        "time, and runs on a smaller key metric set because all metrics are infeasible for it, "
        "which departs from identical inputs. `baro_key_metrics` is BARO on that same set, for a "
        "fair comparison. `baro_midpoint` splits at 50%, which sits next to the true injection in "
        "nearly every case, so it is a **sensitivity check for the window-leak probe and not a "
        "fair score**.",
        "",
    ]
    lines += _table("Unsupervised: group_run", pooled)
    lines += _table("Unsupervised: LOFO per fold", [r for r in folds if r["split"] == "lofo"])
    lines += _table("Unsupervised: LOSO per fold", [r for r in folds if r["split"] == "loso"])
    lines += [
        "### Failures and runtime",
        "",
        "| Method | Failed cases | Mean seconds per case | Max seconds per case |",
        "| --- | --- | --- | --- |",
    ]
    for method, entry in operational.items():
        assert isinstance(entry, dict)
        lines.append(
            f"| {method} | {entry['failed_cases']} | {entry['mean_seconds_per_case']:.3f} "
            f"| {entry['max_seconds_per_case']:.3f} |"
        )
    _write_text(directory / "results.md", "\n".join(lines) + "\n")
    payload: dict[str, object] = {
        "group_run": pooled,
        "folds": folds,
        "operational": operational,
    }
    checksum = load_dataset(root).checksum
    write_result(directory / "results.json", payload, config, config.seed, checksum)
    return payload
