"""Render documents from templates, write provenance, and check that committed files are in sync."""

import re
from dataclasses import dataclass
from pathlib import Path

from cascadelens.models.diagnose import DISCLAIMER
from cascadelens.report.figures import FigureEntry, all_figures
from cascadelens.report.sources import REPRODUCTION_LOG, SOURCES, ReportError, Store
from cascadelens.report.tables import Table, all_tables, markers
from cascadelens.report.values import Value, all_values

TEMPLATES = Path(__file__).parent / "templates"
DOCUMENTS = {
    "README.md": "README.md",
    "REPORT.md": "docs/REPORT.md",
    "MODEL_CARD.md": "MODEL_CARD.md",
    "DEMO_SCRIPT.md": "docs/DEMO_SCRIPT.md",
    "CLAIMS_TODO.md": "docs/CLAIMS_TODO.md",
}
HEADLINE_PATH = "docs/results/headline_table.md"
PROVENANCE_PATH = "docs/results/provenance.md"
TABLES_DIR = "docs/results/tables"
COMMAND = "python -m cascadelens.report build"
PLACEHOLDER = re.compile(r"\{\{([a-z0-9_:]+)\}\}")
BEGIN = "<!-- generated:{name}; regenerate with: " + COMMAND + " -->"
END = "<!-- /generated -->"
CRITERIA = ("S1", "S2", "S3", "S4", "S5", "S6", "S7")


@dataclass(frozen=True)
class Generated:
    """Every Markdown file a build writes, by path relative to the output root."""

    files: dict[str, str]


def _block(table: Table) -> str:
    return "\n".join([BEGIN.format(name=table.name), "", table.markdown(), "", END])


def render(template: str, tables: dict[str, Table], values: dict[str, Value]) -> str:
    """Fill a template. An unknown name is an error, so nothing renders half filled."""

    def replace(match: re.Match[str]) -> str:
        name = match.group(1)
        if name == "disclaimer":
            return DISCLAIMER
        if name.startswith("table:"):
            key = name.removeprefix("table:")
            if key not in tables:
                raise ReportError(f"Unknown table {key}")
            return _block(tables[key])
        if name not in values:
            raise ReportError(f"Unknown value {name}")
        return values[name].text

    return PLACEHOLDER.sub(replace, template)


def provenance(
    store: Store,
    tables: dict[str, Table],
    figures: list[FigureEntry],
    values: dict[str, Value],
) -> str:
    """Return the file that traces every table, figure and value to a result JSON."""
    lines = [
        "# Provenance",
        "",
        f"Generated by `{COMMAND}`. Do not edit by hand.",
        "",
        "## Sources",
        "",
        "| Key | Result JSON | Config hash | Commit | Data checksum | Seed |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for key in SOURCES:
        item = store(key)
        lines.append(
            f"| {key} | `{item.path}` | `{item.config_hash[:12]}` | `{item.git_commit[:12]}` | "
            f"`{item.data_checksum[:12]}` | {item.seed} |"
        )
    lines += [
        "",
        "Commit is the commit each run recorded when it wrote its JSON, which precedes the commit "
        "that added that JSON.",
        "",
        "## Tables",
        "",
        "| Table | Sources |",
        "| --- | --- |",
    ]
    for name, table in tables.items():
        lines.append(f"| {name} | {', '.join(table.sources)} |")
    lines += [
        "",
        "S6 reads `" + REPRODUCTION_LOG + "`.",
        "",
        "## Figures",
        "",
        "| Figure | Source |",
    ]
    lines.append("| --- | --- |")
    lines += [f"| `{item.path}` | {item.source} |" for item in figures]
    lines += ["", "## Values in prose", "", "| Value | Text | Source |", "| --- | --- | --- |"]
    lines += [f"| {name} | {item.text} | {item.source} |" for name, item in sorted(values.items())]
    return "\n".join(lines) + "\n"


def generate(root: Path, draw_to: Path | None = None) -> Generated:
    """Return every generated Markdown file, drawing figures when given a folder."""
    store = Store(root)
    tables = all_tables(store)
    values = all_values(store)
    figures = all_figures(store, draw_to) if draw_to else figure_entries()
    files = {HEADLINE_PATH: _headline_file(tables["headline"], store)}
    for name, table in tables.items():
        files[f"{TABLES_DIR}/{name}.md"] = f"# {table.title}\n\n{table.markdown()}\n"
    files[PROVENANCE_PATH] = provenance(store, tables, figures, values)
    for template, target in DOCUMENTS.items():
        text = (TEMPLATES / template).read_text(encoding="utf-8")
        files[target] = render(text, {**tables, "markers": markers(root, files)}, values)
    return Generated(files)


def _headline_file(table: Table, store: Store) -> str:
    status = store("robustness").metrics["status"]
    return (
        f"# Headline results\n\n**Status: {status}.** The config is not frozen, so these verdicts "
        "preview the pre-registered tests.\n\n" + table.markdown() + "\n"
        if status != "frozen"
        else f"# Headline results\n\n**Status: frozen.**\n\n{table.markdown()}\n"
    )


def figure_entries() -> list[FigureEntry]:
    """Return the figure list without drawing, for the sync check."""
    names = (
        ("leakage", "leakage"),
        ("robustness_p2_supervised", "robustness"),
        ("robustness_p2_unsupervised", "robustness"),
        ("risk_coverage", "calibration"),
    )
    return [FigureEntry(f"docs/results/figures/{name}.png", src) for name, src in names]


def build(root: Path, out: Path | None = None) -> list[Path]:
    """Write every generated file and figure under ``out``, the repository by default."""
    target = out if out is not None else root
    generated = generate(root, target / "docs/results/figures")
    written = []
    for name, text in generated.files.items():
        path = target / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written


def verify(root: Path) -> list[str]:
    """Return what is wrong with the structure of the headline table and provenance file."""
    problems = []
    headline = root / HEADLINE_PATH
    trace = root / PROVENANCE_PATH
    text = headline.read_text(encoding="utf-8") if headline.is_file() else ""
    problems += [f"Headline table lacks {name}" for name in CRITERIA if f"| {name}" not in text]
    traced = trace.read_text(encoding="utf-8") if trace.is_file() else ""
    problems += [f"Provenance lacks {key}" for key in SOURCES if f"| {key} |" not in traced]
    return problems


def _text(path: Path) -> str:
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n")


def check(root: Path) -> list[str]:
    """Return the generated files that differ from what is committed."""
    generated = generate(root)
    return [
        name
        for name, text in generated.files.items()
        if not (root / name).is_file() or _text(root / name) != text
    ]
